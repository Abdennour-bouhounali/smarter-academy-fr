/** No-break space BEFORE each comma between two formulas (a formula never breaks from its comma). */
const SEP = ' ، ';
const rows = (fs) => fs.map((f) => `$${f}$`).join(SEP);
const gcd = (x, y) => (y ? gcd(y, x % y) : x);
/** Euclid's algorithm as the student poses it: [a, b, q, r] down to the remainder 0. */
const divisions = (a, b) => {
  const out = [];
  for (let [x, y] = [Math.max(a, b), Math.min(a, b)]; y; [x, y] = [y, x % y])
    out.push([x, y, Math.floor(x / y), x % y]);
  return out;
};
const divRow = ([a, b, q, r]) => `${a} = ${b} \\times ${q} + ${r}`;
const pgcdTex = (a, b) => `\\mathrm{PGCD}(${a} ; ${b}) = ${gcd(a, b)}`;

