// both (a search downward), a fraction as an exact rational (helpers.mjs `q`, reduced by its own gcd), a decomposition
// by trial division, « irréductible » as PGCD = 1.
import { R, C, q } from './helpers.mjs';

/** the PGCD by its definition: the largest d that divides a and b */
const pgcd = (a, b) => {
  for (let d = Math.min(a, b); d >= 1; d--) if (a % d === 0 && b % d === 0) return d;
  return 1;
};
const irr = (n, d) => pgcd(n, d) === 1;
const isPrime = (n) => {
  if (n < 2) return false;
  for (let d = 2; d * d <= n; d++) if (n % d === 0) return false;
  return true;
};
/** the prime factors (distinct) of n */
const primesOf = (n) => Array.from({ length: n }, (_, i) => i + 1).filter((p) => isPrime(p) && n % p === 0);
const vp = (n, p) => {
  let k = 0;
  while (n % p === 0) {
    n /= p;
    k++;
  }
  return k;
};
