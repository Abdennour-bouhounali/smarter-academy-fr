#!/usr/bin/env node
/**
 * The work order of the « lesson v2 » rollout (docs/reports/LESSON_V2_MASTER_PLAN.md): grade by grade (4AM, then 3AM),
 * term by term — the term's lessons in the order of the school calendar, then the DIRECT prerequisites of those lessons
 * taken from the learning net (core first), each lesson listed once, at its first appearance.
 *
 *   node scripts/v2-rollout-order.mjs            writes docs/curriculum/V2_ROLLOUT_ORDER.md
 *   node scripts/v2-rollout-order.mjs --check    fails when the file is out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { toolsForLesson } from '../packages/core/curriculum/dz/net/learningNet.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'packages/core/curriculum/dz');
const OUT = path.join(ROOT, 'docs/curriculum/V2_ROLLOUT_ORDER.md');
const GRADES = ['4am', '3am'];
const read = (file) => JSON.parse(fs.readFileSync(path.join(DATA, file), 'utf8'));

const termOfWeek = Object.fromEntries(read('calendar/school_2026_2027.json').weeks.map((w) => [w.id, w.term]));
const catalogue = new Map();
for (const grade of ['1am', '2am', '3am', '4am']) {
  for (const lesson of read(`lessons_${grade}_2026_2027.json`).lessons)
    catalogue.set(lesson.code, { ...lesson, grade });
}

function row(code, n, extra = '') {
  const lesson = catalogue.get(code);
  const state = lesson?.status === 'available' ? 'rebuild' : 'new';
  return `| ${n} | \`${code}\` | ${lesson?.title ?? '?'} | ${(lesson?.grade ?? '?').toUpperCase()} | ${state} | ${extra} |`;
}

const seen = new Set();
const lines = [
  '# Lesson v2 — work order',
  '',
  '> GENERATED by `node scripts/v2-rollout-order.mjs` — do not edit. Plan: `docs/reports/LESSON_V2_MASTER_PLAN.md`.',
  '> « rebuild » = the lesson exists and is rebuilt completely; « new » = a catalogue entry generated from scratch.',
  '',
];
let n = 0;
const totals = [];
for (const grade of GRADES) {
  const progression = read(`calendar/progression_${grade}_2026_2027.json`);
  for (const term of [1, 2, 3]) {
    const main = progression.weeks
      .filter((w) => termOfWeek[w.week] === term)
      .flatMap((w) => w.lessons)
      .filter((c) => !seen.has(c));
    main.forEach((c) => seen.add(c));
    const prerequisites = [];
    for (const code of main) {
      for (const tool of toolsForLesson(code, { max: 99 })) {
        const needed = tool.lesson?.code;
        if (!needed || seen.has(needed)) continue;
        seen.add(needed);
        prerequisites.push({ code: needed, weight: tool.weight ?? 'unclassified', neededBy: code });
      }
    }
    const order = { core: 0, unclassified: 1, support: 2 };
    prerequisites.sort((a, b) => order[a.weight] - order[b.weight]);
    lines.push(
      `## ${grade.toUpperCase()} — الفصل ${term}`,
      '',
      `### The term's lessons (${main.length})`,
      '',
      '| # | code | lesson | grade | work | |',
      '|---|---|---|---|---|---|',
    );
    main.forEach((code) => lines.push(row(code, ++n)));
    lines.push(
      '',
      `### Their prerequisites (${prerequisites.length})`,
      '',
      '| # | code | lesson | grade | work | link |',
      '|---|---|---|---|---|---|',
    );
    prerequisites.forEach((p) => lines.push(row(p.code, ++n, `${p.weight} ← \`${p.neededBy}\``)));
    lines.push('');
    totals.push(`${grade.toUpperCase()} T${term}: ${main.length} + ${prerequisites.length}`);
  }
  const unscheduled = (progression.unscheduled ?? []).map((u) => u.code).filter((c) => !seen.has(c));
  if (unscheduled.length) {
    lines.push(
      `## ${grade.toUpperCase()} — not in the school progression (${unscheduled.length})`,
      '',
      '| # | code | lesson | grade | work | |',
      '|---|---|---|---|---|---|',
    );
    unscheduled.forEach((code) => {
      seen.add(code);
      lines.push(row(code, ++n));
    });
    lines.push('');
  }
}
const rebuilt = [...seen].filter((c) => catalogue.get(c)?.status === 'available').length;
lines.splice(5, 0, `**${n} lessons** — ${rebuilt} to rebuild, ${n - rebuilt} new. ${totals.join(' · ')}.`, '');
const text = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) {
    console.error('V2_ROLLOUT_ORDER.md is out of date: run node scripts/v2-rollout-order.mjs');
    process.exit(1);
  }
  console.log('V2_ROLLOUT_ORDER.md is up to date.');
} else {
  fs.writeFileSync(OUT, text);
  console.log(
    `${path.relative(ROOT, OUT)}: ${n} lessons (${rebuilt} to rebuild, ${n - rebuilt} new). ${totals.join(' · ')}`,
  );
}
