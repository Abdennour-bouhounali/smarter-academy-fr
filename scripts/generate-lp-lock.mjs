#!/usr/bin/env node
/**
 * generate-lp-lock — writes packages/core/curriculum/fr/learning_points.lock.json: for every lesson of the catalogue,
 * its grade and the ORDERED texts of its learning points. A learning-point id `<grade>_<lesson>_P<n>` is the n-th text:
 * progress, evidence and reports read the id, so a point that disappears, moves or changes meaning breaks them.
 * The test `learningPointsLock.test.js` fails whenever the catalogue and the lock differ.
 *
 *   npm run generate:lp-lock            # rewrite the lock
 *   npm run generate:lp-lock -- --check # fail if the lock is stale (writes nothing)
 *
 * The rule it applies, lesson by lesson:
 *  - a lesson still `coming_soon` with NO folder under apps/web/src/lessons/college/<grade>/ is not built: its points
 *    may still be re-cut freely, and its lock entry is regenerated as it is;
 *  - a BUILT lesson (it has a folder, or it is `available`) is append-only: its locked points must stay, same text, same
 *    place; a new point is appended after them. Otherwise the script refuses and writes nothing.
 *  - a built lesson that left the catalogue is refused too (its ids would vanish).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'packages/core/curriculum/fr');
const LOCK = join(DATA, 'learning_points.lock.json');
const LESSONS_DIR = join(ROOT, 'apps/web/src/lessons/college');
const GRADES = ['6e', '5e', '4e', '3e'];
const json = (f) => JSON.parse(readFileSync(f, 'utf8'));

/** Every directory name under apps/web/src/lessons/college/<grade>/ (a lesson lives in …/<theme>/<unit>/<lesson>/). */
function folderNames(grade) {
  const names = new Set();
  const walk = (dir, depth) => {
    if (depth > 4 || !existsSync(dir)) return;
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (!e.isDirectory()) continue;
      names.add(e.name);
      walk(join(dir, e.name), depth + 1);
    }
  };
  walk(join(LESSONS_DIR, grade), 0);
  return names;
}

export function buildLock() {
  const lessons = {};
  const built = new Set();
  for (const grade of GRADES) {
    const folders = folderNames(grade);
    for (const l of json(join(DATA, `lessons_${grade}_2026_2027.json`)).lessons) {
      lessons[l.code] = { grade, points: [...l.pointsToLearn] };
      if (folders.has(l.code) || l.status === 'available') built.add(l.code);
    }
  }
  return { lessons, built };
}

export function render(lessons) {
  return `${JSON.stringify(
    {
      _comment:
        'GENERATED by `npm run generate:lp-lock` — the learning points of every lesson, in order: `<grade>_<code>_P<n>` is the n-th text. Append-only once a lesson is built (a folder under apps/web/src/lessons/college/). Guarded by packages/core/curriculum/fr/learningPointsLock.test.js.',
      lessons,
    },
    null,
    2,
  )}\n`;
}

/** The violations of the append-only rule, for the built lessons. */
export function violations(previous, next, built) {
  const out = [];
  for (const [code, old] of Object.entries(previous)) {
    if (!built.has(code)) continue;
    const now = next[code];
    if (!now) {
      out.push(`${code}: a built lesson left the catalogue — its ${old.points.length} learning-point ids would vanish`);
      continue;
    }
    old.points.forEach((text, i) => {
      if (now.points[i] !== text) {
        out.push(`${old.grade}_${code}_P${i + 1}: « ${text} » is now « ${now.points[i] ?? '(gone)'} » — a built lesson's point never moves, disappears or changes`);
      }
    });
  }
  return out;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const previous = existsSync(LOCK) ? json(LOCK).lessons : {};
  const { lessons, built } = buildLock();
  const text = render(lessons);
  if (process.argv.includes('--check')) {
    if (!existsSync(LOCK) || readFileSync(LOCK, 'utf8') !== text) {
      console.error('✗ learning_points.lock.json is stale: npm run generate:lp-lock');
      process.exit(1);
    }
    console.log(`✓ learning-point lock up to date (${Object.keys(lessons).length} lessons)`);
    process.exit(0);
  }
  const bad = violations(previous, lessons, built);
  if (bad.length) {
    console.error('✗ refused — the learning points of a BUILT lesson are append-only:');
    for (const b of bad) console.error(`  - ${b}`);
    console.error('Append a new point after the last one instead; a reorder is forbidden once a lesson is built.');
    process.exit(1);
  }
  const free = Object.keys(lessons).filter((c) => !built.has(c)).length;
  writeFileSync(LOCK, text);
  console.log(
    `✓ packages/core/curriculum/fr/learning_points.lock.json — ${Object.keys(lessons).length} lessons ` +
      `(${built.size} built: append-only; ${free} not built yet: their points may still be re-cut and the lock regenerated freely)`,
  );
}
